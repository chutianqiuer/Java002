/*
 * =====================================================
 * 传统方式示例：CoffeeMaker
 * =====================================================
 *
 * 【演示目的】
 *
 * 这个类与TeaMaker类似，进一步演示传统方式的耦合问题。
 * CoffeeMaker也直接在自己的代码中new了Water对象，
 * 展示了这种模式的问题具有普遍性。
 *
 * 【对比分析】
 *
 * TeaMaker和CoffeeMaker都自己创建Water对象：
 * - 如果我们想统计一共创建了多少个Water对象，非常困难
 * - 如果我们想复用Water对象（单例模式），需要额外编码
 * - 如果我们想在创建Water时添加日志或监控，需要修改每个类
 *
 * 这些问题说明传统方式下，对象的管理非常不灵活，
 * 难以实现横切关注点（如日志、监控、事务等）。
 *
 * 【Spring IoC的解决思路】
 *
 * 1. 集中管理：所有对象的创建都在IoC容器中管理
 * 2. 声明式依赖：对象只需要声明需要什么，不需要自己创建
 * 3. 生命周期控制：容器负责对象的创建、初始化、销毁
 * 4. 可配置：可以通过配置改变对象之间的依赖关系，无需修改代码
 *
 * =====================================================
 */
package com.example.ioc;

/**
 * 咖啡制作器（传统方式）
 *
 * 演示传统编程方式：对象自己负责创建依赖
 * 与TeaMaker形成对比，展示问题的普遍性
 */
public class CoffeeMaker {

    /**
     * 制作咖啡的方法
     *
     * 【同样的问题】
     * 这里也直接new了一个Water对象，和TeaMaker一样存在耦合问题。
     * 如果TeaMaker和CoffeeMaker都各自创建Water对象，
     * 我们无法统一管理这些Water对象的生命周期。
     */
    public void makeCoffee() {
        // ============================================
        // 同样问题：直接创建依赖对象
        // ============================================

        // CoffeeMaker也自己创建Water对象
        // 问题与TeaMaker完全一样：
        // - 强耦合于Water的具体实现
        // - 无法复用Water实例
        // - 无法统一管理生命周期
        Water water = new Water();

        // 烧水的过程
        water.boil();

        // 制作咖啡
        System.out.println("【传统方式】CoffeeMaker: 用" + water.getDescription() + "制作了一杯咖啡");

        /*
         * 思考：如果TeaMaker和CoffeeMaker都想用"纯净水"而不是"自来水"，
         * 我们需要修改两个类的方法。
         *
         * 如果有100个类都自己创建Water对象，那修改工作量会非常大。
         *
         * 使用Spring IoC后，只需要在配置中改变bean的定义，所有使用Water的类
         *都会自动使用新的实现，真正实现"一处修改，处处生效"。
         */
    }
}
