/*
 * =====================================================
 * 传统方式示例：TeaMaker
 * =====================================================
 *
 * 【演示目的】
 *
 * 这个类演示了传统编程方式中对象自己创建依赖的问题。
 * TeaMaker在自己的代码中直接new了一个Water对象，
 * 这种方式导致了高度的耦合。
 *
 * 【问题分析】
 *
 * 1. 耦合性高：
 *    - TeaMaker类直接依赖Water类的具体实现
 *    - 如果Water类的构造函数变化，TeaMaker也需要修改
 *    - 如果想使用不同的水源（如矿泉水、纯净水），需要修改TeaMaker代码
 *
 * 2. 难以单元测试：
 *    - 如果要测试TeaMaker的逻辑，无法轻松替换Water
 *    - 无法mock Water对象进行测试
 *
 * 3. 依赖关系不明确：
 *    - 在TeaMaker类外部，很难知道它依赖Water
 *    - 代码阅读者需要查看TeaMaker的完整实现才能了解依赖
 *
 * 4. 对象管理问题：
 *    - 每次调用makeTea都会new一个新的Water对象
 *    - 无法复用Water实例
 *    - 无法控制Water对象的生命周期
 *
 * 【解决方案】
 *
 * 使用Spring IoC容器，将Water对象的创建和管理交给容器，
 * TeaMaker只需要声明它需要Water，由容器负责注入。
 * 这就是依赖注入（DI）的核心思想。
 *
 * =====================================================
 */
package com.example.ioc;

/**
 * 茶饮制作器（传统方式）
 *
 * 演示传统编程方式：对象自己负责创建依赖
 */
public class TeaMaker {

    /**
     * 制作茶的方法
     *
     * 【问题所在】
     * 这里直接new了一个Water对象，导致TeaMaker与Water强耦合。
     * 如果Water的创建逻辑变了，或者需要用不同的Water实现，
     * 都得修改这个方法。
     */
    public void makeTea() {
        // ============================================
        // 问题演示：直接创建依赖对象
        // ============================================

        // 在传统方式中，对象自己负责创建它的依赖
        // 这行代码展示了：
        //   1. TeaMaker知道Water的具体实现类
        //   2. TeaMaker负责Water对象的生命周期
        //   3. 这种硬编码导致无法轻松替换Water实现
        Water water = new Water();

        // 烧水的过程
        water.boil();

        // 制作茶
        System.out.println("【传统方式】TeaMaker: 用" + water.getDescription() + "制作了一杯茶");

        /*
         * 这里的Water是具体实现，而不是接口/抽象
         * 如果系统需要支持多种水源（如矿泉水、纯净水、泉水），
         * 就需要修改这段代码，违反了"开闭原则"（对扩展开放，对修改关闭）
         */
    }
}

/**
 * 水类（简化示例）
 *
 * 演示一个简单的依赖类
 */
class Water {

    /**
     * 烧水方法
     */
    public void boil() {
        System.out.println("Water: 把水烧开...");
    }

    /**
     * 获取水的描述
     * @return 水的描述信息
     */
    public String getDescription() {
        return "普通自来水";
    }
}
