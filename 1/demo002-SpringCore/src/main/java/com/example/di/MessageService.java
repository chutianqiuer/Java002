/*
 * =====================================================
 * 依赖注入示例：消息服务接口
 * =====================================================
 *
 * 【接口的作用】
 *
 * 定义接口是依赖注入的关键步骤。
 * 通过面向接口编程，我们可以在不修改Consumer代码的情况下，
 * 改变具体使用哪个消息服务的实现。
 *
 * 【为什么需要接口】
 *
 * 1. 解耦：Consumer只依赖于接口，不关心具体实现
 * 2. 可替换：可以轻松切换不同的实现（如从Email切换到SMS）
 * 3. 可测试：可以用mock实现替换真实实现，方便单元测试
 * 4. 清晰：接口定义了组件之间的契约
 *
 * 【Spring IoC与接口】
 *
 * 在Spring中，我们通常将业务接口（如MessageService）定义为接口，
 * 然后提供多个实现（如EmailService、SmsService）。
 *
 * 通过配置或注解，我们可以决定使用哪个实现，
 * 而Consumer不需要知道具体是哪个实现。
 *
 * =====================================================
 */
package com.example.di;

/**
 * 消息服务接口
 *
 * 定义发送消息的抽象方法。
 * 任何实现这个接口的类都可以作为消息服务的提供者。
 *
 * 【设计原则】
 *
 * 这个接口遵循了"接口隔离原则"和"依赖倒置原则"：
 * - 接口隔离：只定义发送消息这一个方法，职责单一
 * - 依赖倒置：高层模块（Consumer）依赖抽象（接口），而不是具体实现
 */
public interface MessageService {

    /**
     * 发送消息
     *
     * @param message 要发送的消息内容
     * @param recipient 接收者（可以是邮箱地址、手机号等）
     * @return 发送是否成功
     */
    boolean sendMessage(String message, String recipient);
}
